#!/usr/bin/env node
/* ============================================================
   Adds (or refreshes) the link-preview tags that Facebook, LinkedIn,
   X and WhatsApp read when someone shares a page, so shared links show
   a picture, title and description instead of a bare URL.

   Run from the site folder after adding or renaming a page:
       node tools/add-social-tags.js

   It reads each page's <title>, meta description and canonical link,
   and writes the tags between the SOCIAL-TAGS markers in <head>.
   Safe to run as many times as you like. To change the preview
   picture, replace assets/images/social/share-card.png (1200x630).
   ============================================================ */
const fs = require("fs");
const path = require("path");

const SITE = "https://baldwinterneypress.com";
const IMAGE = SITE + "/assets/images/social/share-card.png";
const IMAGE_ALT = "Baldwin Terney Press — children's books, Cyber Elementary and the Managed Security Buyers Guide";
const SKIP = new Set(["404.html"]);

const root = path.join(__dirname, "..");
const esc = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const unesc = (s) => s.replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&#39;/g, "'");

let count = 0;
for (const file of fs.readdirSync(root).filter((f) => f.endsWith(".html") && !SKIP.has(f))) {
  const full = path.join(root, file);
  let html = fs.readFileSync(full, "utf8");
  const title = unesc(((html.match(/<title>([^<]*)<\/title>/i) || [])[1] || "Baldwin Terney Press").trim());
  const desc = unesc(((html.match(/<meta\s+name="description"\s+content="([^"]*)"/i) || [])[1] || "").trim());
  const url = (html.match(/<link\s+rel="canonical"\s+href="([^"]*)"/i) || [])[1] || `${SITE}/${file === "index.html" ? "" : file}`;

  const block = [
    "<!-- SOCIAL-TAGS:START (generated by tools/add-social-tags.js) -->",
    `<meta property="og:type" content="website" />`,
    `<meta property="og:site_name" content="Baldwin Terney Press" />`,
    `<meta property="og:title" content="${esc(title)}" />`,
    `<meta property="og:description" content="${esc(desc)}" />`,
    `<meta property="og:url" content="${esc(url)}" />`,
    `<meta property="og:image" content="${IMAGE}" />`,
    `<meta property="og:image:width" content="1200" />`,
    `<meta property="og:image:height" content="630" />`,
    `<meta property="og:image:alt" content="${esc(IMAGE_ALT)}" />`,
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${esc(title)}" />`,
    `<meta name="twitter:description" content="${esc(desc)}" />`,
    `<meta name="twitter:image" content="${IMAGE}" />`,
    "<!-- SOCIAL-TAGS:END -->",
  ].join("\n");

  if (/<!-- SOCIAL-TAGS:START[\s\S]*?SOCIAL-TAGS:END -->/.test(html)) {
    html = html.replace(/<!-- SOCIAL-TAGS:START[\s\S]*?SOCIAL-TAGS:END -->/, block);
  } else if (/<link\s+rel="canonical"[^>]*>/i.test(html)) {
    html = html.replace(/(<link\s+rel="canonical"[^>]*>)/i, `$1\n${block}`);
  } else {
    html = html.replace(/<\/head>/i, `${block}\n</head>`);
  }
  fs.writeFileSync(full, html);
  count++;
}
console.log(`Social tags written to ${count} pages.`);
